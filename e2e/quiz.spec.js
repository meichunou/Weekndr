import {test,expect} from '@playwright/test';
test('complete quiz, back navigation, email validation and optional consent',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:'Find my weekend escape'}).click();
 await page.getByRole('button',{name:'€100–€150'}).click();
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await expect(page.getByRole('heading',{name:'What’s your weekend budget?'})).toBeVisible();
 await page.getByRole('button',{name:'€100–€150'}).click();
 await page.getByRole('button',{name:'Train City center to city center'}).click();
 await page.getByRole('button',{name:/Chill & cozy ☕/}).click();
 await expect(page.getByRole('heading',{name:'Hello, Bruges.'})).toBeVisible();
 await expect(page.getByRole('checkbox')).not.toBeChecked();
 await page.getByRole('button',{name:'Unlock my free itinerary'}).click();
 await expect(page.getByRole('alert')).toContainText('Enter a valid email');
 await page.getByLabel('Your university or personal email').fill('student@example.com');
 await page.getByRole('button',{name:'Unlock my free itinerary'}).click();
 await expect(page.getByRole('heading',{name:'Your weekend is sorted! 🎉'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'DAY 2 — Sunday'})).toBeVisible();
 const stored=await page.evaluate(()=>localStorage.getItem('weekndr-demo-events'));
 expect(stored).not.toContain('student@example.com');expect(stored).toContain('itinerary_unlocked');expect(stored).not.toContain('marketing_consent_given');
 await page.getByRole('button',{name:'Demo analytics ↗'}).click();
 await expect(page.getByRole('heading',{name:'Local demo metrics'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`test-results/${test.info().project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'Plan another weekend'}).click();
 await expect(page.getByRole('heading',{name:'What’s your weekend budget?'})).toBeVisible();expect(errors).toEqual([]);
});
